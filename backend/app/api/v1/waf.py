def _json_safe_rule(rule: WafRule) -> dict:
    """Convert a WafRule instance into a JSON-safe snapshot dict."""
    safe = {}
    for k, v in rule.__dict__.items():
        if k.startswith("_"):
            continue
        if hasattr(v, "isoformat"):
            safe[k] = v.isoformat()
        elif v is None or isinstance(v, (str, int, float, bool, list, dict)):
            safe[k] = v
        else:
            safe[k] = str(v)
    return safe


def _waf_rule_version_max(db: Session) -> int:
    """Return the per-rule max snapshot count (0 = unlimited).

    Prefers the DB-backed setting, falling back to the env var default.
    """
    default = str(settings.WAF_RULE_VERSION_MAX_PER_RULE)
    try:
        return int(get_setting(db, "waf_rule_version_max_per_rule", default) or default)
    except (TypeError, ValueError):
        return settings.WAF_RULE_VERSION_MAX_PER_RULE


def _prune_waf_rule_versions(db: Session, waf_rule_id: int) -> int:
    """Delete oldest snapshots beyond the per-rule max for the given rule.

    Returns the number of snapshots removed. No-op when max is 0 (unlimited).
    """
    max_keep = _waf_rule_version_max(db)
    if max_keep <= 0:
        return 0
    total = db.query(WafRuleVersion).filter(WafRuleVersion.waf_rule_id == waf_rule_id).count()
    if total <= max_keep:
        return 0
    to_remove = (
        db.query(WafRuleVersion)
        .filter(WafRuleVersion.waf_rule_id == waf_rule_id)
        .order_by(WafRuleVersion.created_at.desc())
        .offset(max_keep)
        .all()
    )
    for v in to_remove:
        db.delete(v)
    db.commit()
    return len(to_remove)


@router.post("/waf/rules/{rid}/refresh-rule-set")
def refresh_rule_set(rid: int, db: Session = Depends(get_db), user=Depends(require_write), _=Depends(rate_limit)):
    """Manually trigger a download of a remote rule set."""
    rule = db.get(WafRule, rid)
    if not rule:
        raise HTTPException(status_code=404, detail="WAF rule not found")
    if rule.rule_set != "remote":
        raise HTTPException(status_code=400, detail="Rule set is not 'remote'")
    if not rule.rule_set_url:
        raise HTTPException(status_code=400, detail="No rule set URL configured")
    from ...services.rule_set_downloader import download_rule_set
    ok = download_rule_set(db, rule)
    if ok:
        from ...services import coraza_config
        coraza_config.write_coraza_spoa_config(db)
    return {"ok": ok, "error": rule.rule_set_last_error}


